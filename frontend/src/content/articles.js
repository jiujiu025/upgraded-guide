const allArticles = [...helpArticles, ...resources]

export function findArticle(slug) {
  return allArticles.find((item) => item.slug === slug) || null
}

export function articleNeighbours(slug) {
  const index = allArticles.findIndex((item) => item.slug === slug)
  if (index < 0) return { prev: null, next: null }
  return { prev: allArticles[index - 1] || null, next: allArticles[index + 1] || null }
}
